import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import * as fs from 'fs/promises';
import * as path from 'path';
import * as os from 'os';

// A renamed app id once made boot regenerate every tenant's shared.env empty,
// and tenants lost their variables and secrets on the next restart. These cover
// the other ways to get there: a lost or legacy store, or a store without the app.

let root: string;
let appsDir: string;
let dataDir: string;

const envVarsFile = () => path.join(dataDir, 'env-vars.json');
const overridesFile = () => path.join(dataDir, 'tenant-env-overrides.json');
const sharedEnv = (app: string, id: string) => path.join(appsDir, app, 'tenants', id, 'shared.env');
const exists = (p: string) => fs.access(p).then(() => true, () => false);
const LIVE_SHARED_ENV = '# Shared environment variables\n# Generated by Overwatch: x\n\nAPI_TOKEN=live-secret\nLOG_LEVEL=info\n';
const envVar = (key: string, value: string) => ({ key, value, sensitive: false, createdAt: 'x', updatedAt: 'x' });

beforeEach(async () => {
  root = await fs.mkdtemp(path.join(os.tmpdir(), 'overwatch-store-loss-'));
  appsDir = path.join(root, 'apps');
  dataDir = path.join(root, 'data');
  await fs.mkdir(dataDir, { recursive: true });
  vi.doMock('../config', () => ({ getAppsDir: () => appsDir, getDataDir: () => dataDir }));
});

afterEach(async () => {
  vi.resetModules();
  vi.restoreAllMocks();
  vi.doUnmock('../config');
  await fs.rm(root, { recursive: true, force: true });
});

async function tenant(app: string, id: string, shared?: string) {
  const p = path.join(appsDir, app, 'tenants', id);
  await fs.mkdir(p, { recursive: true });
  await fs.writeFile(path.join(p, '.env'), 'TENANT_DOMAIN=x\n');
  if (shared !== undefined) await fs.writeFile(path.join(p, 'shared.env'), shared);
  return p;
}

async function stores(envVars: unknown, overrides: unknown = {}) {
  await fs.writeFile(envVarsFile(), JSON.stringify(envVars));
  await fs.writeFile(overridesFile(), JSON.stringify(overrides));
}

describe('a missing env store while tenants still have variables', () => {
  it.each(['env-vars.json', 'tenant-env-overrides.json'])('refuses to start %s from empty', async (missing) => {
    await tenant('demo', 'a', LIVE_SHARED_ENV);
    await stores({ demo: [envVar('API_TOKEN', 'live-secret')] });
    await fs.rm(path.join(dataDir, missing));
    const { regenerateAllSharedEnvFiles, listEnvVars, getTenantOverrides, setEnvVar, setTenantOverride } = await import('../services/envVars');

    const err: any = await regenerateAllSharedEnvFiles().catch(e => e);
    expect(err).toBeInstanceOf(Error);
    expect(err.message).toContain(missing);
    expect(err.message).toMatch(/snapshot restore/);
    expect(err.status).toBe(500);
    expect(err.expose).toBe(true);
    expect(err.clientMessage).not.toContain(root);

    const read = missing === 'env-vars.json' ? listEnvVars('demo') : getTenantOverrides('demo', 'a');
    await expect(read).rejects.toThrow(missing);
    const write = missing === 'env-vars.json' ? setEnvVar('demo', 'NEW', 'v') : setTenantOverride('demo', 'a', 'NEW', 'v');
    await expect(write).rejects.toThrow(missing);

    expect(await fs.readFile(sharedEnv('demo', 'a'), 'utf-8')).toBe(LIVE_SHARED_ENV);
    expect(await exists(path.join(dataDir, missing))).toBe(false);
  });

  it('creates both stores as {} (0600) when no tenant has variables yet, and regenerates', async () => {
    await tenant('demo', 'a');
    await tenant('demo', 'b', '# Shared environment variables\n\n');
    const { regenerateAllSharedEnvFiles } = await import('../services/envVars');

    expect(await regenerateAllSharedEnvFiles()).toBe(2);
    for (const f of [envVarsFile(), overridesFile()]) {
      expect(JSON.parse(await fs.readFile(f, 'utf-8'))).toEqual({});
      expect((await fs.stat(f)).mode & 0o777).toBe(0o600);
    }
  });

  it('lets the first tenant be created on an install without stores', async () => {
    await tenant('demo', 'first');
    const { generateSharedEnvFile } = await import('../services/envVars');
    await generateSharedEnvFile('demo', 'first');
    expect(await exists(sharedEnv('demo', 'first'))).toBe(true);
  });

  it('creates a missing store under its lock: a reader waits for a writer and returns what it wrote', async () => {
    const { withFileLock } = await import('../services/fileLock');
    const { listEnvVars } = await import('../services/envVars');
    let release!: () => void;
    const gate = new Promise<void>(r => { release = r; });
    let acquired!: () => void;
    const held = new Promise<void>(r => { acquired = r; });
    const writer = withFileLock('env-vars', async () => {
      acquired();
      await gate;
      await fs.writeFile(envVarsFile(), JSON.stringify({ demo: [envVar('WRITTEN', 'by-writer')] }));
    });
    await held;

    const reader = listEnvVars('demo');
    await new Promise(r => setTimeout(r, 80));
    expect(await exists(envVarsFile())).toBe(false);
    release();
    await writer;
    expect((await reader).map(v => v.key)).toEqual(['WRITTEN']);
    expect(JSON.parse(await fs.readFile(envVarsFile(), 'utf-8')).demo[0].value).toBe('by-writer');
  });
});

describe('a legacy flat-array env store', () => {
  it.each([
    ['env-vars.json', [envVar('API_TOKEN', 'live-secret')], {}],
    ['tenant-env-overrides.json', {}, [{ tenantId: 'a', overrides: [] }]],
  ])('%s is refused with instructions, not read as empty', async (name, envVars, overrides) => {
    await tenant('demo', 'a', LIVE_SHARED_ENV);
    await stores(envVars, overrides);
    const before = await fs.readFile(path.join(dataDir, name), 'utf-8');
    const { regenerateAllSharedEnvFiles, getEffectiveEnvVars } = await import('../services/envVars');

    const err: any = await regenerateAllSharedEnvFiles().catch(e => e);
    expect(err.message).toContain(name);
    expect(err.message).toMatch(/legacy/i);
    expect(err.message).toMatch(/overwatch migrate up/);
    await expect(getEffectiveEnvVars('demo', 'a')).rejects.toThrow(/legacy/i);

    expect(await fs.readFile(sharedEnv('demo', 'a'), 'utf-8')).toBe(LIVE_SHARED_ENV);
    expect(await fs.readFile(path.join(dataDir, name), 'utf-8')).toBe(before);
  });
});

describe('shared.env regeneration for an app neither store knows', () => {
  it('keeps a tenant shared.env holding variables, logs it, and still regenerates other apps', async () => {
    await tenant('renamed', 'a', LIVE_SHARED_ENV);
    await tenant('known', 'b', LIVE_SHARED_ENV);
    await stores({ known: [envVar('LOG_LEVEL', 'debug')], 'old-name': [envVar('API_TOKEN', 'live-secret')] });
    const error = vi.spyOn(console, 'error').mockImplementation(() => {});
    const { regenerateAllSharedEnvFiles } = await import('../services/envVars');

    expect(await regenerateAllSharedEnvFiles()).toBe(1);

    expect(await fs.readFile(sharedEnv('renamed', 'a'), 'utf-8')).toBe(LIVE_SHARED_ENV);
    expect(await fs.readFile(sharedEnv('known', 'b'), 'utf-8')).toContain('LOG_LEVEL=debug');
    const logged = error.mock.calls.map(c => String(c[0])).join('\n');
    expect(logged).toContain('renamed/a');
    expect(logged).toMatch(/env-vars\.json/);
  });

  it('regenerateTenantSharedEnv and generateSharedEnvFile keep it too', async () => {
    await tenant('renamed', 'a', LIVE_SHARED_ENV);
    await stores({});
    vi.spyOn(console, 'error').mockImplementation(() => {});
    const { regenerateTenantSharedEnv, generateSharedEnvFile } = await import('../services/envVars');

    expect(await regenerateTenantSharedEnv('renamed', 'a')).toEqual({ busy: false, kept: true });
    await generateSharedEnvFile('renamed', 'a');
    expect(await fs.readFile(sharedEnv('renamed', 'a'), 'utf-8')).toBe(LIVE_SHARED_ENV);
  });

  it('regenerates a shared.env that holds no variables', async () => {
    await tenant('renamed', 'a', '# Shared environment variables\n# Generated by Overwatch: x\n\n');
    await stores({});
    const { regenerateAllSharedEnvFiles } = await import('../services/envVars');
    expect(await regenerateAllSharedEnvFiles()).toBe(1);
  });
});

describe('legitimate removals still reach shared.env', () => {
  it('an app entry that is an empty list empties the file', async () => {
    await tenant('demo', 'a', LIVE_SHARED_ENV);
    await stores({ demo: [] });
    const { regenerateAllSharedEnvFiles } = await import('../services/envVars');
    expect(await regenerateAllSharedEnvFiles()).toBe(1);
    expect(await fs.readFile(sharedEnv('demo', 'a'), 'utf-8')).not.toContain('API_TOKEN');
  });

  it('deleting the last global variable through the service', async () => {
    await tenant('demo', 'a');
    await stores({});
    const { setEnvVar, deleteEnvVar, regenerateAllSharedEnvFiles } = await import('../services/envVars');
    await setEnvVar('demo', 'ONLY', 'v');
    await regenerateAllSharedEnvFiles('demo');
    expect(await fs.readFile(sharedEnv('demo', 'a'), 'utf-8')).toContain('ONLY=v');
    await deleteEnvVar('demo', 'ONLY');
    await regenerateAllSharedEnvFiles('demo');
    expect(await fs.readFile(sharedEnv('demo', 'a'), 'utf-8')).not.toContain('ONLY');
  });

  it('deleting the last tenant-only override of an app without global variables', async () => {
    await tenant('demo', 'a');
    await stores({});
    const { setTenantOverride, deleteTenantOverride, regenerateTenantSharedEnv } = await import('../services/envVars');
    await setTenantOverride('demo', 'a', 'TENANT_ONLY', 'v');
    await regenerateTenantSharedEnv('demo', 'a');
    expect(await fs.readFile(sharedEnv('demo', 'a'), 'utf-8')).toContain('TENANT_ONLY=v');
    await deleteTenantOverride('demo', 'a', 'TENANT_ONLY');
    expect(await regenerateTenantSharedEnv('demo', 'a')).toEqual({ busy: false });
    expect(await fs.readFile(sharedEnv('demo', 'a'), 'utf-8')).not.toContain('TENANT_ONLY');
  });
});
