#!/usr/bin/env node
// Inline every file under templates/ into src/generated/embeddedTemplates.ts as
// a map of relative-path → string. This avoids pkg's asset handling entirely
// (pkg's static analyser couldn't see our dynamic path.resolve at runtime and
// silently dropped the glob-listed assets, producing "file not included" at
// execution time on the pkg'd binary). By inlining we sidestep both issues.

import { promises as fs } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(__filename), '..');
const TEMPLATES_DIR = path.join(ROOT, 'templates');
const OUT_DIR = path.join(ROOT, 'src', 'generated');
const OUT_FILE = path.join(OUT_DIR, 'embeddedTemplates.ts');

async function walk(dir, base = dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const out = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...(await walk(full, base)));
    } else if (entry.isFile()) {
      out.push(path.relative(base, full));
    }
  }
  return out;
}

function escapeBackticks(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true });
  const files = await walk(TEMPLATES_DIR);
  const lines = [
    '// AUTO-GENERATED by scripts/embed-templates.mjs — DO NOT EDIT.',
    '// Run `npm run build` (which invokes embed-templates) to refresh.',
    '',
    'export const EMBEDDED_TEMPLATES: Record<string, string> = {',
  ];
  for (const rel of files) {
    const content = await fs.readFile(path.join(TEMPLATES_DIR, rel), 'utf-8');
    const posixRel = rel.split(path.sep).join('/');
    lines.push(`  ${JSON.stringify(posixRel)}: \`${escapeBackticks(content)}\`,`);
  }
  lines.push('};', '');
  await fs.writeFile(OUT_FILE, lines.join('\n'), 'utf-8');
  console.log(`[embed-templates] wrote ${files.length} file(s) to ${path.relative(ROOT, OUT_FILE)}`);
}

main().catch(err => {
  console.error('[embed-templates] failed:', err);
  process.exit(1);
});
